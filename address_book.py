import pandas as pd  # подключаем пандас чтобы работать с таблицей
# создаем пустую таблицу с нужными столбцами
a = pd.DataFrame(columns=["ФИО", "Адрес", "Телефон", "Дата рождения"])
while True:  # бесконечный цикл чтобы программа не закрывалась
    print("Адресная книга") 
    print("1 - Просмотреть все записи")
    print("2 - Добавить запись")
    print("3 - Изменить запись")
    print("4 - Удалить запись")
    print("5 - Выйти")
    v = input("Выберите действие (1-5): ")  # выбрать действие
    if v == "1":
        if len(a) == 0:  # проверяем пустая ли таблица
            print("Адресная книга пуста")
        else:
            print(a)  # вывод таблицы
    elif v == "2":
        # спрашиваем все поля и добавляем новую строку
        fio = input("Введите ФИО: ")
        adres = input("Введите адрес: ")
        telefon = input("Введите телефон: ")
        data = input("Введите дату рождения: ")
        novaya = pd.DataFrame([[fio, adres, telefon, data]], columns=a.columns) # создаем из одной строки маленькую таблицу и присоединяем к основной
        a = pd.concat([a, novaya], ignore_index=True)  # ignore_index чтобы номера шли подряд
        print("Запись добавлена")
    elif v == "3":
        if len(a) == 0: # проверяем пустая ли таблица
            print("Адресная книга пуста")
        else:
            print(a)
            n = int(input("Введите номер записи для изменения: "))
            if n in a.index:  # проверяем есть ли такая строка
                print("Если поле менять не надо - оставьте его пустым")
                for stolbec in a.columns:  # идем по всем столбцам по очереди
                    novoe = input("Новое значение для поля " + stolbec + ": ")
                    if novoe != "":  # если что-то ввели - меняем
                        a.loc[n, stolbec] = novoe
                print("Запись изменена")
            else:
                print("Такой записи нет")
    elif v == "4":
        if len(a) == 0: # проверяем пустая ли таблица
            print("Адресная книга пуста")
        else:
            print(a)
            n = int(input("Введите номер записи для удаления: "))
            if n in a.index:
                a = a.drop(n)  # удаляем строку по номеру
                a = a.reset_index(drop=True)  # перенумеровываем заново чтобы не было пропусков
                print("Запись удалена")
            else:
                print("Такой записи нет")
    elif v == "5":
        print("Выходим")
        break  # выходим из цикла и программа заканчивается
    else:
        print("Неверный выбор. Попробуйте снова.")